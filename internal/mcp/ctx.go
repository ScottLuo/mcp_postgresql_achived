package mcp

import (
	"context"
)

// contextKey is an unexported type for context keys in this package.
// Using a distinct type prevents collisions with keys from other packages.
type contextKey struct{}

// toolCtxKey is the context key under which a *ToolContext is stored.
var toolCtxKey = contextKey{}

// ToolContext is the common execution context passed to all tool handlers.
//
// It carries the request-scoped context plus metadata about which target
// database is being addressed and the request/operation identifiers for
// audit and traceability.
//
// Invariant: ToolContext must never contain database passwords, DSNs, or
// other sensitive connection information. Credentials remain inside the
// DatabaseManager and are never propagated to tool handlers.
type ToolContext struct {
	// Context is the request-scoped context, cancelled on timeout or
	// context cancellation.
	Context context.Context

	// Target is the resolved database target alias (e.g., "development").
	Target string

	// RequestID is a unique identifier for this MCP tool call request.
	// Generated by the server on receipt; used for audit correlation.
	RequestID string

	// OperationID is a unique identifier for the underlying database
	// operation. May differ from RequestID if a single request triggers
	// multiple operations.
	OperationID string
}

// NewToolContext creates a ToolContext with the given parameters.
func NewToolContext(ctx context.Context, target, requestID, operationID string) *ToolContext {
	return &ToolContext{
		Context:     ctx,
		Target:      target,
		RequestID:   requestID,
		OperationID: operationID,
	}
}

// WithToolContext stores tc in ctx and returns the new context.
func WithToolContext(ctx context.Context, tc *ToolContext) context.Context {
	return context.WithValue(ctx, toolCtxKey, tc)
}

// FromContext retrieves the ToolContext stored by WithToolContext.
// Returns nil if no ToolContext was set on ctx.
func FromContext(ctx context.Context) *ToolContext {
	tc, _ := ctx.Value(toolCtxKey).(*ToolContext)
	return tc
}
